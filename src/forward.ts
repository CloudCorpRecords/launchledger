/**
 * launchledger core: a forwarding client for the hosted
 * Launchelion MCP server, a catalogue of live, launched
 * AI tools.
 *
 * No catalogue data lives on this machine. tools/list is
 * answered from the literal definitions below, which
 * reproduce a live capture of the upstream server word
 * for word (name, title, description and inputSchema
 * exactly as captured, including the `$schema` marker
 * each captured inputSchema carries). A tools/call
 * travels upstream over a streamable-HTTP JSON-RPC
 * session: an initialize POST, a
 * notifications/initialized POST, then the tools/call
 * POST, carrying the Mcp-Session-Id response header on
 * later requests when the upstream issues one. The
 * session opens lazily on the first forwarded call and
 * is reused for the client's lifetime.
 *
 * The surface is a labelled subset of the capture. Two
 * captured tools are deliberately NOT registered here:
 * `submit_tool`, which submits a new listing on behalf
 * of its maker carrying the maker's email and returns a
 * claim/sign-up URL, and `create_checkout`, which
 * creates a Stripe checkout URL for a paid listing
 * add-on and so originates a purchase flow. The kept
 * `list_offers` read only publishes the add-ons' names,
 * effects and USD prices; it buys nothing itself.
 *
 * The endpoint is pinned to
 * https://launchelion.com/api/mcp/mcp and may be replaced
 * with the LAUNCHELION_MCP_URL environment variable
 * (that override is a labelled reconstruction). The
 * registry record declares NO headers on the remote: no
 * auth header is ever sent, under any environment.
 *
 * A successful upstream result is returned exactly as
 * received, isError flag and extra fields included.
 * Failures — an upstream JSON-RPC error, a non-2xx
 * status, a body that cannot be parsed, or a fetch that
 * throws or times out — become an isError result whose
 * text begins with `launchledger error:` (that rendering
 * is a labelled reconstruction). Replies may be plain
 * JSON or SSE (`data:` lines); the JSON-RPC message
 * whose id matches the request wins.
 */
